def lookup_longitude(city: str):
    """按城市名查经度；支持带省市前缀的写法。找不到返回 None。"""
    if not city:
        return None
    name = city.strip().replace("市", "").replace("省", "")
    # 直接命中
    for key, lon in CITY_DB.items():
        if key in name or name in key:
            return lon
    # 取末段再试（"四川省成都" → "成都"）
    for seg in reversed(name.split()):
        for key, lon in CITY_DB.items():
            if key in seg or seg in key:
                return lon
    return None


def equation_of_time_minutes(dt: datetime) -> float:
    """均时差（分钟），Spencer 近似公式，误差 < 1 分钟。"""
    n = dt.timetuple().tm_yday
    b = 2 * math.pi * (n - 81) / 364.0
    return 9.87 * math.sin(2 * b) - 7.53 * math.cos(b) - 1.5 * math.sin(b)


def true_solar_time(dt: datetime, city: str):
    """返回 (校正后的datetime, 说明文本, 是否校正)。"""
    lon = lookup_longitude(city)
    if lon is None:
        return dt, "未识别出生地，未做真太阳时校正（按北京时间直接排盘）", False
    corr = (lon - 120.0) * 4.0 + equation_of_time_minutes(dt)
    adjusted = dt + timedelta(minutes=corr)
    note = (
        f"出生地识别为「{city}」（东经 {lon:.1f}°）。"
        f"经度校正 {(lon - 120.0) * 4.0:+.1f} 分钟，"
        f"均时差 {equation_of_time_minutes(dt):+.1f} 分钟，"
        f"合计 {corr:+.1f} 分钟：{dt:%H:%M} → 真太阳时 {adjusted:%H:%M}"
    )
    return adjusted, note, True
